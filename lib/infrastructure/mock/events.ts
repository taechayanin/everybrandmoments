let seq = 0;
function ev(
  accountId: AccountId,
  momentType: MomentCode,
  subMoment: string,
  stakeholders: Stakeholder[],
  triggerSource: TriggerSource,
  triggerDetail: string,
  detectedAt: string,
  expectedEventDate: string,
  s: [number, number, number, number, number], // fit/30 intent/25 timing/20 wallet/15 rel/10
  potentialWalletMin: number,
  potentialWalletMax: number,
  recommendedSolutionIds: SolutionId[],
  recommendedAction: string,
  ownerId: UserId,
  status: MomentEventStatus,
  nextExpectedMoment: MomentCode,
  channel?: Channel,
): MomentEvent {
  seq += 1;
  return {
    id: `ME-2026-${String(seq).padStart(6, "0")}` as MomentEventId,
    accountId,
    momentType,
    subMoment,
    stakeholders,
    triggerSource,
    triggerDetail,
    detectedAt,
    expectedEventDate,
    score: {
      businessFit: s[0],
      intent: s[1],
      timing: s[2],
      wallet: s[3],
      relationship: s[4],
    },
    potentialWalletMin,
    potentialWalletMax,
    recommendedSolutionIds,
    recommendedAction,
    ownerId,
    status,
    nextExpectedMoment,
    channel,
  };
}

